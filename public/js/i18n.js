let currentLang = 'uz';

function initI18n() {
    try {
        const saved = localStorage.getItem('callcenter_lang');
        if (saved && (saved === 'uz' || saved === 'ru')) {
            currentLang = saved;
        } else {
            currentLang = 'uz';
        }
    } catch (e) {
        currentLang = 'uz';
    }
    applyTranslations();
}

function getCurrentLang() {
    return currentLang;
}

function t(key, fallback = '') {
    const dict = I18N_TRANSLATIONS[currentLang] || I18N_TRANSLATIONS.uz;
    if (dict && dict[key] !== undefined) {
        return dict[key];
    }
    const defDict = I18N_TRANSLATIONS.uz;
    if (defDict && defDict[key] !== undefined) {
        return defDict[key];
    }
    return fallback || key;
}

/**
 * Translate with placeholder substitution, e.g. tf('logs_page', { page: 1, total: 3 })
 */
function tf(key, params, fallback = '') {
    let str = t(key, fallback);
    if (params && typeof params === 'object') {
        Object.keys(params).forEach(k => {
            str = str.split('{' + k + '}').join(params[k]);
        });
    }
    return str;
}

function switchLanguage(lang) {
    if (lang !== 'uz' && lang !== 'ru') return;
    currentLang = lang;
    try {
        localStorage.setItem('callcenter_lang', lang);
    } catch (e) {}

    applyTranslations();

    // Trigger custom event for dynamic components (charts, modals, table renderers)
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function applyTranslations() {
    document.documentElement.setAttribute('lang', currentLang);

    // Update Language Buttons Active State
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === currentLang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    // Translate DOM elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const text = t(key);
        if (text) {
            if (el.getAttribute('data-i18n-html') === 'true') {
                el.innerHTML = text;
            } else {
                el.textContent = text;
            }
        }
    });

    // Translate Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const text = t(key);
        if (text) el.placeholder = text;
    });

    // Translate Titles / Tooltips
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        const text = t(key);
        if (text) el.title = text;
    });
}

// Automatically initialize when DOM is ready
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initI18n);
} else {
    initI18n();
}
